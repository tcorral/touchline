const catalogs: Record<Locale, Catalog> = {en, es, nl};
const STORAGE_KEY = 'touchline-locale';
let locale: Locale = readStored();
const listeners = new Set<() => void>();

function readStored(): Locale {
  try {
    const value = localStorage.getItem(STORAGE_KEY);
    if (value === 'en' || value === 'es' || value === 'nl') return value;
  } catch { /* private mode or disabled storage */ }
  return 'en';
}

export function getLocale(): Locale {
  return locale;
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const template = catalogs[locale][key] ?? catalogs.en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

export function matchesAnyLocale(key: MessageKey, value: string): boolean {
  return (Object.keys(catalogs) as Locale[]).some(code => catalogs[code][key] === value);
}

export function onLocaleChange(listener: () => void): void {
  listeners.add(listener);
}

export function applyI18n(root: ParentNode = document): void {
  document.documentElement.lang = locale;
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n as MessageKey;
    if (key in catalogs.en) el.textContent = t(key);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml as MessageKey;
    if (key in catalogs.en) el.innerHTML = t(key);
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach(el => {
    const key = el.dataset.i18nAria as MessageKey;
    if (key in catalogs.en) el.setAttribute('aria-label', t(key));
  });
}

export function setLocale(next: string): void {
  if (next !== 'en' && next !== 'es' && next !== 'nl') return;
  if (next === locale) return;
  locale = next;
  try { localStorage.setItem(STORAGE_KEY, next); } catch { /* ignore quota or private mode */ }
  const select = document.querySelector<HTMLSelectElement>('#locale');
  if (select) select.value = locale;
  applyI18n();
  listeners.forEach(listener => listener());
}

export function bootI18n(): void {
  applyI18n();
  const select = document.querySelector<HTMLSelectElement>('#locale');
  if (!select || select.dataset.bound === '1') return;
  select.dataset.bound = '1';
  select.value = locale;
  select.addEventListener('change', () => setLocale(select.value));
}

if (typeof document !== 'undefined') bootI18n();
